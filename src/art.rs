pub fn logo_rgba(size: u32) -> Vec<u8> {
    let s = size as usize;
    let k = (s / 16).max(1);
    let mut px = vec![0u8; s * s * 4];
    let r = (s / 6) as i32;
    let si = s as i32;
    for y in 0..si {
        for x in 0..si {
            let cx = if x < r { r } else if x >= si - r { si - 1 - r } else { x };
            let cy = if y < r { r } else if y >= si - r { si - 1 - r } else { y };
            let (dx, dy) = (x - cx, y - cy);
            if dx * dx + dy * dy <= r * r {
                let i = (y as usize * s + x as usize) * 4;
                px[i..i + 4].copy_from_slice(&[33, 30, 28, 255]);
            }
        }
    }
    let ox = (s - 12 * k) / 2;
    let oy = (s - 14 * k) / 2;
    let mut put = |cx: usize, cy: usize, c: [u8; 3]| {
        for yy in 0..k {
            for xx in 0..k {
                let i = ((oy + cy * k + yy) * s + ox + cx * k + xx) * 4;
                px[i..i + 4].copy_from_slice(&[c[0], c[1], c[2], 255]);
            }
        }
    };
    let hex = |h: &str| {
        let v = u32::from_str_radix(h.trim_start_matches('#'), 16).unwrap_or(0);
        [(v >> 16) as u8, (v >> 8) as u8, v as u8]
    };
    let hat = &DEFS[0];
    for (r, row) in hat.rows.iter().enumerate() {
        for (c, ch) in row.chars().enumerate() {
            if let Some((_, h)) = hat.colors.iter().find(|(key, _)| *key == ch) {
                put(c, r, hex(*h));
            }
        }
    }
    for (r, row) in IDLE_STAND.iter().step_by(2).enumerate() {
        for (c, ch) in row.chars().step_by(2).enumerate() {
            match ch {
                '#' => put(c, r + 6, [CRAB.r(), CRAB.g(), CRAB.b()]),
                'E' => put(c, r + 6, [EYE.r(), EYE.g(), EYE.b()]),
                _ => {}
            }
        }
    }
    px
}

